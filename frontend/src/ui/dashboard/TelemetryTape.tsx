import { useEffect, useRef, useState } from 'react'
import { LayoutGroup, motion, useInView, useReducedMotion } from 'motion/react'
import { ArrowUpRight, Radio, X, FileText } from 'lucide-react'
import { Link } from 'react-router-dom'
import HudSwitch from './HudSwitch'

type EventKind = 'intake' | 'collision' | 'sla'
interface DemoEvent { id: string; kind: EventKind; caseId: string; title: string; detail: string; bureau: string }
const EVENTS: DemoEvent[] = [
  { id: 'intake-9812', kind: 'intake', caseId: 'RB-2026-9812', title: 'Infrastructure deficiency logged', detail: 'Illustrative intake: laboratory facilities require officer review. This sample has not been filed in the case register.', bureau: 'Regulation Bureau' },
  { id: 'collision-8819', kind: 'collision', caseId: 'PGRC-2026-8819', title: '94.2% overlap suggested', detail: 'Illustrative related complaints describe the same institution and issue. An officer would inspect both records before linking them.', bureau: 'RB / PGRC' },
  { id: 'sla-2048', kind: 'sla', caseId: 'RB-2026-2048', title: '48-hour review horizon flagged', detail: 'Illustrative warning: a pending grievance approaches its configured deadline. This is a simulated event, not a live SLA alert.', bureau: 'Regulation Bureau' },
  { id: 'intake-9820', kind: 'intake', caseId: 'PGRC-2026-9820', title: 'Student grievance received', detail: 'Illustrative receipt: a student submission enters the review queue with its original source reference preserved.', bureau: 'PGRC' },
  { id: 'collision-8821', kind: 'collision', caseId: 'RB-2026-8821', title: 'Related institutional case identified', detail: 'Illustrative collision: similar allegations occur in two bureau queues. Lead nomination remains an officer decision.', bureau: 'RB / PGRC' },
  { id: 'sla-2052', kind: 'sla', caseId: 'PGRC-2026-2052', title: 'Pending action needs escalation review', detail: 'Illustrative escalation: the assigned officer reviews a delayed action. No notification or external call is generated by this tape.', bureau: 'PGRC' },
]
const FILTERS = [{ id: 'all', label: 'All' }, { id: 'sla', label: 'High-Risk SLA' }, { id: 'collision', label: 'Collisions' }] as const
const color = (kind: EventKind) => kind === 'sla' ? '#FFB4AB' : kind === 'collision' ? '#FFD180' : '#80CBC4'

function InvestigationDrawer({ event, onClose }: { event: DemoEvent | null; onClose: () => void }) {
  const ref = useRef<HTMLDialogElement>(null)
  const reduced = useReducedMotion()
  useEffect(() => {
    const dialog = ref.current
    if (!dialog || !event) return
    const opener = document.activeElement
    dialog.showModal()
    return () => { dialog.close(); if (opener instanceof HTMLElement && opener.isConnected) opener.focus({ preventScroll: true }) }
  }, [event])
  return (
    <dialog ref={ref} aria-labelledby="demo-investigation-title" onCancel={onClose} onClick={e => { if (e.target === e.currentTarget) onClose() }} className="cn-investigation">
      {event && <motion.article layoutId={reduced ? undefined : `telemetry-${event.id}`} initial={{ opacity: 0, x: reduced ? 0 : 32 }} animate={{ opacity: 1, x: 0 }} transition={{ duration: reduced ? 0 : 0.25 }} className="flex min-h-full flex-col bg-[#F6F5F1] p-6 sm:p-8">
        <div className="flex items-center justify-between border-b border-[#DAD6CC] pb-5"><span className="font-mono text-[10px] uppercase tracking-wider text-[#8A4B08]">Synthetic investigation preview</span><button type="button" autoFocus onClick={onClose} aria-label="Close investigation" className="rounded-lg border border-[#DAD6CC] p-2 hover:bg-white"><X size={18} /></button></div>
        <div className="mt-10 flex h-12 w-12 items-center justify-center rounded-xl bg-[#1F3A5F] text-white"><FileText size={22} /></div>
        <p className="mt-6 font-mono text-xs text-[#5B6068]">{event.caseId}</p>
        <h2 id="demo-investigation-title" className="mt-3 text-3xl font-semibold leading-tight text-[#1F3A5F]">{event.title}</h2>
        <p className="mt-6 text-sm leading-relaxed text-[#5B6068]">{event.detail}</p>
        <dl className="mt-8 space-y-4 rounded-xl border border-[#DAD6CC] bg-white p-5 text-sm"><div className="flex justify-between gap-4"><dt className="text-[#5B6068]">Bureau</dt><dd>{event.bureau}</dd></div><div className="flex justify-between gap-4"><dt className="text-[#5B6068]">Source</dt><dd>Local demonstration</dd></div><div className="flex justify-between gap-4"><dt className="text-[#5B6068]">Case data written</dt><dd>None</dd></div></dl>
        <p className="mt-6 text-xs leading-relaxed text-[#5B6068]">This example explains the workflow. Use the case register to investigate actual records in your authorized scope.</p>
        <Link to="/cases" onClick={onClose} className="mt-8 flex items-center justify-between rounded-lg bg-[#1F3A5F] px-4 py-3 text-sm text-white">Open case register <ArrowUpRight size={16} /></Link>
      </motion.article>}
    </dialog>
  )
}

export default function TelemetryTape() {
  const [filter, setFilter] = useState<'all' | 'sla' | 'collision'>('all')
  const [moving, setMoving] = useState(true)
  const [hovered, setHovered] = useState(false)
  const [focused, setFocused] = useState(false)
  const [keyboardFocus, setKeyboardFocus] = useState(false)
  const [selected, setSelected] = useState<DemoEvent | null>(null)
  const [documentVisible, setDocumentVisible] = useState(!document.hidden)
  const reduced = useReducedMotion()
  const ref = useRef<HTMLElement>(null)
  const inView = useInView(ref)
  const events = EVENTS.filter(event => filter === 'all' || event.kind === filter)
  const staticMode = reduced || !moving || keyboardFocus
  const running = !staticMode && !hovered && !focused && !selected && inView && documentVisible
  useEffect(() => {
    const change = () => setDocumentVisible(!document.hidden)
    document.addEventListener('visibilitychange', change)
    return () => document.removeEventListener('visibilitychange', change)
  }, [])

  return (
    <LayoutGroup id="statutory-telemetry">
      <section ref={ref} aria-labelledby="telemetry-title" className="overflow-hidden rounded-xl border border-[#314760] bg-[#14233A] text-[#E8EDF3]">
        <div className="flex flex-wrap items-center justify-between gap-4 border-b border-white/10 px-5 py-4">
          <div><h2 id="telemetry-title" className="flex items-center gap-2 font-mono text-xs font-semibold"><Radio size={14} className="text-[#80CBC4]" /> Statutory event tape</h2><p className="mt-1 text-[10px] text-[#A9B6C6]">Synthetic examples · local simulation · select an event to inspect</p></div>
          <div className="flex flex-wrap items-center gap-3">
            <div aria-label="Filter simulated events" className="flex gap-1 rounded-lg bg-white/5 p-1">{FILTERS.map(item => <button key={item.id} type="button" aria-pressed={filter === item.id} onClick={() => setFilter(item.id)} className="relative rounded px-2.5 py-1.5 text-[10px]">{filter === item.id && <motion.span layoutId={reduced ? undefined : 'telemetry-filter'} className="absolute inset-0 rounded bg-white/15" />}<span className="relative">{item.label}</span></button>)}</div>
            <span className="rounded-lg bg-[#F6F5F1] px-2"><HudSwitch checked={moving && !reduced} disabled={Boolean(reduced)} onChange={setMoving} label="Animate tape" /></span>
          </div>
        </div>
        <div className={staticMode ? 'overflow-x-auto p-4' : 'overflow-hidden py-4'} onMouseEnter={() => setHovered(true)} onMouseLeave={() => setHovered(false)} onFocusCapture={e => { setFocused(true); if (e.target.matches(':focus-visible')) setKeyboardFocus(true) }} onBlurCapture={e => { if (!e.currentTarget.contains(e.relatedTarget)) { setFocused(false); setKeyboardFocus(false) } }}>
          <div key={filter} className={`flex w-max ${staticMode ? '' : 'cn-ticker-track'}`} style={{ animationPlayState: running ? 'running' : 'paused' }}>
            {[0, ...(staticMode ? [] : [1])].map(copy => <div key={copy} aria-hidden={copy === 1 || undefined} inert={copy === 1} className="flex gap-3 pr-3">
              {events.map(event => <motion.button key={event.id} type="button" layoutId={copy === 0 && !reduced ? `telemetry-${event.id}` : undefined} onClick={() => setSelected(event)} className="w-[280px] shrink-0 rounded-lg border border-white/15 bg-white/5 px-4 py-3 text-left hover:border-white/40 sm:w-[310px]"><span className="font-mono text-[10px]" style={{ color: color(event.kind) }}>[{event.caseId}]</span><span className="mt-2 block text-xs">{event.title}</span></motion.button>)}
            </div>)}
          </div>
        </div>
        <InvestigationDrawer event={selected} onClose={() => setSelected(null)} />
      </section>
    </LayoutGroup>
  )
}
